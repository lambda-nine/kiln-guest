def replacement_cases(prepared):
    """Normative expected/observed verdicts. tests exercise them on real Linux exec."""
    vector = prepared['substitutions']['executables']
    cases = []
    for role, expected in vector.items():
        observed = {name: expected[name] for name in ['role', 'st_dev', 'st_ino', 'bytes', 'sha256']}
        cases.append({'role': role, 'race': 'retained-fd-after-source-and-name-replacement',
                      'expected': expected, 'observed': observed, 'accept': True})
        cases.append({'role': role, 'race': 'installed-identical-bytes-new-inode', 'expected': expected,
                      'observed': {**observed, 'st_ino': expected['st_ino'] + 1000}, 'accept': False})
        cases.append({'role': role, 'race': 'other-device-same-inode', 'expected': expected,
                      'observed': {**observed, 'st_dev': expected['st_dev'] + 1}, 'accept': False})
        cases.append({'role': role, 'race': 'installed-name-different-bytes', 'expected': expected,
                      'observed': {**observed, 'st_ino': expected['st_ino'] + 2000, 'sha256': '99' * 32}, 'accept': False})
        cases.append({'role': role, 'race': 'size-only-disagreement', 'expected': expected,
                      'observed': {**observed, 'bytes': expected['bytes'] + 1}, 'accept': False})
    return {'cases': cases, 'boundaries': ['before-S-exec-J', 'before-J-exec-V', 'before-formatter-exec', 'before-worker-exec'],
            'argv_and_prior_digest': 'insufficient', 'post_C1': 'charged-until-AbsentFenced', 'C0': 'zero-session-side-effects'}


