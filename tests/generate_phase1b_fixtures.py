def generate(dest):
    dest = Path(dest)
    legacy = (FIXTURES/LEGACY).read_bytes()  # Projected once from the real refused manifest.
    if dest.exists():
        for entry in dest.iterdir():
            shutil.rmtree(entry) if entry.is_dir() else entry.unlink()
    (dest/'bundle').mkdir(parents=True)
    (dest/'executables').mkdir()
    (dest/LEGACY).write_bytes(legacy)
    (dest/'README.md').write_text(README)
    (dest/'jailer-patch.fixture').write_bytes(f1.FIXTURE_JAILER_PATCH)

    policy = p1.contract()
    pins = {}
    for role in p1.ROLES:
        data = fixture_elf(role)
        (dest/'executables'/role).write_bytes(data)
        pins[role] = {**record(data), 'format': 'static-elf', 'dependencies': []}
    artifacts = {}
    for name in p1.ARTIFACTS:
        data = fixture_elf(name) if name in ('kiln', 'kilnd-guest-broker') else f'B1 test artifact: {name}\n'.encode()
        (dest/'bundle'/name).write_bytes(data)
        artifacts[name] = record(data)
    manifest = {**p1.manifest_fields(policy), 'schema': f1.FIXTURE_MANIFEST_SCHEMA, 'fixture_only': True, 'artifacts': artifacts, 'executables': pins,
                'inputs': {**p1.manifest_inputs(policy), **f1.fixture_inputs(artifacts)}}
    write_json(dest/'bundle/manifest.json', manifest)
    raw = (dest/'bundle/manifest.json').read_bytes()
    approved = p1.digest(raw)
    write_json(dest/'contract.json', policy)

    vector = {role: {**{name: pin[name] for name in ['bytes', 'sha256']}, 'installation_generation': 1}
              for role, pin in pins.items()}
    unequal = substitutions(vector, 300001, 300002, 300003, 300004)
    equal = substitutions(vector, 300005, 300005, 300006, 300006)
    write_json(dest/'substitutions.json', unequal)
    write_json(dest/'substitutions-equal-ids.json', equal)
    prepared = f1.plan(raw, approved, unequal).document
    write_json(dest/'plan.json', prepared)
    write_json(dest/'plan-equal-ids.json', f1.plan(raw, approved, equal).document)
    (dest/'identity.bin').write_bytes(p1.identity_block(prepared))
    jail_root = {'st_dev': 41, 'st_ino': 7, 'mount_id': 512}
    write_json(dest/'bootstrap.json', {'plan_generation': 1, 'jail_root_identity': jail_root,
                                       'record': json.loads(p1.bootstrap_record(prepared, 1, jail_root))})
    backend = 'fc-' + unequal['allocation_id']
    write_json(dest/'vmm-argv.json', ['/firecracker', '--id', backend, '--start-time-us', '1793318400000000',
                                      '--start-time-cpu-us', '0', '--parent-cpu-time-us', '1250',
                                      '--no-api', '--config-file', '/config.json'])
    (dest/'vmm-status.txt').write_text(status_text(300001, 300002))
    write_json(dest/'replacement-cases.json', replacement_cases(prepared))
    write_json(dest/'negative-cases.json', negative_cases(pins))

    from b1_conformance import generate as conformance
    write_json(dest/'conformance.json', conformance(dest))

    files = sorted(str(path.relative_to(dest)) for path in dest.rglob('*') if path.is_file())
    write_json(dest/'digests.json', {'approved_manifest_sha256': approved,
                                     'launch_sha256': p1.launch_digest(prepared),
                                     'plan_sha256': p1.plan_digest(prepared),
                                     'files': {name: p1.digest((dest/name).read_bytes()) for name in files}})


if __name__ == '__main__':
    generate(Path(sys.argv[1]) if len(sys.argv) > 1 else FIXTURES)
