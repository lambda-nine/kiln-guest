def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, sort_keys=True, indent=2) + '\n')


def fixture_elf(tag):
    """One PT_LOAD at 0x400000 whose entry is `b .`; the trailing tag differentiates inodes' bytes."""
    code = bytes.fromhex('00000014') + tag.encode() + b'\0'
    ident = b'\x7fELF\x02\x01\x01' + b'\0' * 9
    header = struct.pack('<16sHHIQQQIHHHHHH', ident, 2, 183, 1, 0x400078, 64, 0, 0, 64, 56, 1, 0, 0, 0)
    size = 120 + len(code)
    return header + struct.pack('<IIQQQQQQ', 1, 5, 0, 0x400000, 0x400000, size, size, 4096) + code


def record(data):
    return {'bytes': len(data), 'sha256': p1.digest(data)}


