def mutation(name, path, value, why):
    return {'name': name, 'path': path, 'value': value, 'why': why}


def removal(name, path, why):
    return {'name': name, 'path': path, 'remove': True, 'why': why}


def apply_mutation(manifest, case):
    """Applied identically by this suite and kilnd's fixture test."""
    target = manifest
    for part in case['path'][:-1]:
        target = target[part]
    last = case['path'][-1]
    if case.get('remove'):
        del target[last]
    elif isinstance(target, list) and last == len(target):
        target.append(case['value'])
    else:
        target[last] = case['value']


